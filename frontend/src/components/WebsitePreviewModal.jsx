import React, { useState } from "react";
import { X, ExternalLink, Monitor, Tablet, Smartphone, Sparkles } from "lucide-react";
import { getPrototypeRenderUrl } from "../services/api";

export default function WebsitePreviewModal({ lead, onClose }) {
  const [viewport, setViewport] = useState("desktop"); // desktop, tablet, mobile

  if (!lead) return null;

  const renderUrl = getPrototypeRenderUrl(lead.id);

  const getViewportWidth = () => {
    switch (viewport) {
      case "mobile":
        return "max-w-[400px]";
      case "tablet":
        return "max-w-[768px]";
      default:
        return "w-full";
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm animate-fadeIn">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-6xl h-[90vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header bar */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-800 bg-slate-950/60">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-lg bg-indigo-500/10 border border-indigo-500/20 text-indigo-400">
              <Sparkles className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="text-base font-bold text-white">
                  {lead.business_name} — Single-Page Prototype
                </h3>
                <span className="text-[10px] uppercase font-bold tracking-wider px-2 py-0.5 rounded bg-indigo-500/20 text-indigo-300">
                  Live Preview
                </span>
              </div>
              <p className="text-xs text-slate-400">
                Customized proposal demo generated by Agent 4
              </p>
            </div>
          </div>

          {/* Viewport switchers & Actions */}
          <div className="flex items-center gap-3">
            <div className="flex items-center bg-slate-800 rounded-lg p-1 border border-slate-700">
              <button
                onClick={() => setViewport("desktop")}
                className={`p-1.5 rounded ${
                  viewport === "desktop"
                    ? "bg-indigo-600 text-white"
                    : "text-slate-400 hover:text-white"
                }`}
                title="Desktop View"
              >
                <Monitor className="w-4 h-4" />
              </button>
              <button
                onClick={() => setViewport("tablet")}
                className={`p-1.5 rounded ${
                  viewport === "tablet"
                    ? "bg-indigo-600 text-white"
                    : "text-slate-400 hover:text-white"
                }`}
                title="Tablet View"
              >
                <Tablet className="w-4 h-4" />
              </button>
              <button
                onClick={() => setViewport("mobile")}
                className={`p-1.5 rounded ${
                  viewport === "mobile"
                    ? "bg-indigo-600 text-white"
                    : "text-slate-400 hover:text-white"
                }`}
                title="Mobile View"
              >
                <Smartphone className="w-4 h-4" />
              </button>
            </div>

            <a
              href={renderUrl}
              target="_blank"
              rel="noreferrer"
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold border border-slate-700 transition"
            >
              <ExternalLink className="w-3.5 h-3.5" />
              <span>Open Standalone</span>
            </a>

            <button
              onClick={onClose}
              className="p-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-400 hover:text-white transition"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Viewport iframe canvas */}
        <div className="flex-1 bg-slate-950 p-4 flex justify-center items-center overflow-auto">
          <div
            className={`h-full transition-all duration-300 rounded-xl overflow-hidden shadow-2xl border border-slate-800 bg-white ${getViewportWidth()}`}
          >
            <iframe
              src={renderUrl}
              title={`Prototype for ${lead.business_name}`}
              className="w-full h-full border-0"
            />
          </div>
        </div>
      </div>
    </div>
  );
}
